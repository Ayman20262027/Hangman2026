export function getRandomWord(difficulty: Difficulty, category?: string): WordItem {
  let filtered = WORD_COLLECTION.filter((w) => w.difficulty === difficulty);

  if (category && category !== 'All Categories') {
    const matched = filtered.filter((w) => w.category === category);
    if (matched.length > 0) {
      filtered = matched;
    }
  }

  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || WORD_COLLECTION[0];
}
